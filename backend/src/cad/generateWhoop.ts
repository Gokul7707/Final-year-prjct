import { execFile } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(__dirname, '../../..');
const WHOOP_SCAD = path.join(PROJECT_ROOT, 'cad/whoop/whoop.scad');
const OUTPUT_DIR = path.join(PROJECT_ROOT, 'output/chassis');

const OPENSCAD_PATH =
  process.env.OPENSCAD_PATH || 'C:\\Program Files\\OpenSCAD\\openscad.com';

export interface WhoopParams {
  wheelbase?: number;
  motorCageDiameter?: number;
  motorCageDepth?: number;
  batteryDimensions?: [number, number];
  strutCount?: number;
  wallThickness?: number;
}

const PRESETS: Record<string, WhoopParams> = {
  '75mm': {
    wheelbase: 75,
    motorCageDiameter: 43,
    motorCageDepth: 15,
    batteryDimensions: [15.6, 7.4],
    strutCount: 4,
    wallThickness: 1.75,
  },
  '65mm': {
    wheelbase: 65,
    motorCageDiameter: 33,
    motorCageDepth: 13.5,
    batteryDimensions: [11.9, 7.0],
    strutCount: 3,
    wallThickness: 1.5,
  },
};

function buildScadSource(params: WhoopParams): string {
  const lines = [
    'include <whoop.scad>;',
    '',
    '// Auto-generated by GenesisAI',
  ];

  if (params.wheelbase != null) lines.push(`whoop_xy_wheelbase = ${params.wheelbase};`);
  if (params.motorCageDiameter != null) lines.push(`motor_cage_xy_diameter = ${params.motorCageDiameter};`);
  if (params.motorCageDepth != null) lines.push(`motor_cage_z_depth = ${params.motorCageDepth};`);
  if (params.batteryDimensions != null) {
    lines.push(`battery_cage_xz_dimensions = [${params.batteryDimensions[0]}, ${params.batteryDimensions[1]}];`);
  }
  if (params.strutCount != null) {
    lines.push(`motor_cage_strut_count = ${params.strutCount};`);
    if (params.strutCount === 3) lines.push('motor_cage_strut_z_angle = 0;');
  }
  if (params.wallThickness != null) {
    lines.push(`motor_base_z_thickness = ${params.wallThickness};`);
    lines.push(`motor_cage_xyz_thickness = ${params.wallThickness};`);
    lines.push(`battery_cage_xz_thickness = ${params.wallThickness};`);
  }

  lines.push('', 'whoop();');
  return lines.join('\n');
}

export async function generateWhoopChassis(
  presetOrParams: string | WhoopParams = '75mm'
): Promise<{ scadPath: string; stlPath: string; params: WhoopParams }> {
  const params =
    typeof presetOrParams === 'string'
      ? PRESETS[presetOrParams] ?? PRESETS['75mm']
      : presetOrParams;

  await mkdir(OUTPUT_DIR, { recursive: true });

  const tag = params.wheelbase ?? 'custom';
  const scadPath = path.join(OUTPUT_DIR, `whoop_${tag}mm.scad`);
  const stlPath = path.join(OUTPUT_DIR, `whoop_${tag}mm.stl`);

  const scadSource = buildScadSource(params);
  await writeFile(scadPath, scadSource, 'utf-8');

  await execFileAsync(OPENSCAD_PATH, ['-I', path.dirname(WHOOP_SCAD), '-o', stlPath, scadPath], {
    timeout: 120_000,
  });

  return { scadPath, stlPath, params };
}

export { PRESETS };
