import { execFile } from 'node:child_process';
import { access, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);

const __dirname = path.dirname(fileURLToPath(import.meta.url));

/** Project root: env override for Docker, else three levels up from src/cad or dist/cad. */
const PROJECT_ROOT = process.env.PROJECT_ROOT || path.resolve(__dirname, '../../..');
const WHOOP_SCAD = process.env.WHOOP_SCAD || path.join(PROJECT_ROOT, 'cad/whoop/whoop.scad');
const OUTPUT_DIR = process.env.OUTPUT_DIR || path.join(PROJECT_ROOT, 'output/chassis');

const OPENSCAD_CANDIDATES = [
  process.env.OPENSCAD_PATH,
  'openscad',
  'C:\\Program Files\\OpenSCAD\\openscad.com',
  'C:\\Program Files\\OpenSCAD\\openscad.exe',
  '/usr/bin/openscad',
].filter(Boolean) as string[];

export interface WhoopParams {
  wheelbase?: number;
  motorCageDiameter?: number;
  motorCageDepth?: number;
  batteryDimensions?: [number, number];
  strutCount?: number;
  wallThickness?: number;
}

const PRESETS: Record<string, WhoopParams> = {
  '75mm': {
    wheelbase: 75,
    motorCageDiameter: 43,
    motorCageDepth: 15,
    batteryDimensions: [15.6, 7.4],
    strutCount: 4,
    wallThickness: 1.75,
  },
  '65mm': {
    wheelbase: 65,
    motorCageDiameter: 33,
    motorCageDepth: 13.5,
    batteryDimensions: [11.9, 7.0],
    strutCount: 3,
    wallThickness: 1.5,
  },
};

function buildScadSource(params: WhoopParams): string {
  // Absolute include — OpenSCAD 2021 (Debian) has no `-I` flag.
  const whoopInclude = WHOOP_SCAD.replace(/\\/g, '/');
  const lines = [
    `include <${whoopInclude}>;`,
    '',
    '// Auto-generated by GenesisAI job runner',
  ];

  if (params.wheelbase != null) lines.push(`whoop_xy_wheelbase = ${params.wheelbase};`);
  if (params.motorCageDiameter != null) lines.push(`motor_cage_xy_diameter = ${params.motorCageDiameter};`);
  if (params.motorCageDepth != null) lines.push(`motor_cage_z_depth = ${params.motorCageDepth};`);
  if (params.batteryDimensions != null) {
    lines.push(`battery_cage_xz_dimensions = [${params.batteryDimensions[0]}, ${params.batteryDimensions[1]}];`);
  }
  if (params.strutCount != null) {
    lines.push(`motor_cage_strut_count = ${params.strutCount};`);
    if (params.strutCount === 3) lines.push('motor_cage_strut_z_angle = 0;');
  }
  if (params.wallThickness != null) {
    lines.push(`motor_base_z_thickness = ${params.wallThickness};`);
    lines.push(`motor_cage_xyz_thickness = ${params.wallThickness};`);
    lines.push(`battery_cage_xz_thickness = ${params.wallThickness};`);
  }

  lines.push('', 'whoop();');
  return lines.join('\n');
}

async function resolveOpenScad(): Promise<string> {
  for (const candidate of OPENSCAD_CANDIDATES) {
    try {
      if (candidate === 'openscad') {
        await execFileAsync(candidate, ['--version'], { timeout: 10_000 });
        return candidate;
      }
      await access(candidate);
      return candidate;
    } catch {
      /* try next */
    }
  }
  throw new Error(
    'OpenSCAD not found. Install OpenSCAD and set OPENSCAD_PATH, or use the Docker backend image with OpenSCAD.'
  );
}

/**
 * Parametric whoop chassis → STL via OpenSCAD CLI.
 * This is the Phase 1 CAD pillar — not a mock.
 */
export async function generateWhoopChassis(
  presetOrParams: string | WhoopParams = '75mm',
  jobTag?: string
): Promise<{ scadPath: string; stlPath: string; params: WhoopParams; stlFilename: string; scadFilename: string }> {
  const params =
    typeof presetOrParams === 'string'
      ? PRESETS[presetOrParams] ?? PRESETS['75mm']
      : presetOrParams;

  await mkdir(OUTPUT_DIR, { recursive: true });

  const tag = `${params.wheelbase ?? 'custom'}${jobTag ? `_${jobTag}` : ''}`;
  const scadFilename = `whoop_${tag}mm.scad`;
  const stlFilename = `whoop_${tag}mm.stl`;
  const scadPath = path.join(OUTPUT_DIR, scadFilename);
  const stlPath = path.join(OUTPUT_DIR, stlFilename);

  const scadSource = buildScadSource(params);
  await writeFile(scadPath, scadSource, 'utf-8');

  const openscad = await resolveOpenScad();
  const libDir = path.dirname(WHOOP_SCAD);
  await execFileAsync(openscad, ['-o', stlPath, scadPath], {
    timeout: 180_000,
    env: {
      ...process.env,
      // Library path for any relative includes inside whoop.scad
      OPENSCADPATH: [libDir, process.env.OPENSCADPATH].filter(Boolean).join(path.delimiter),
    },
    cwd: libDir,
  });

  return { scadPath, stlPath, params, stlFilename, scadFilename };
}

export { PRESETS, OUTPUT_DIR, PROJECT_ROOT };
